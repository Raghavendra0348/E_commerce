import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";
import { createHash } from "node:crypto";

// Read public markup only. No account-only download endpoints or scripts run.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = "https://sitestyleguide.com/amazon.in";
const decode = (value) => value.replace(/&(quot|#039|apos|lt|gt|amp);/g, (_, entity) => ({
  quot: '"', "#039": "'", apos: "'", lt: "<", gt: ">", amp: "&",
})[entity]);
async function download(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(20000) });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}
const html = (await download(source)).toString("utf8");
function block(id) {
  const match = html.match(new RegExp(`<pre[^>]*id="${id}"[^>]*>([\\s\\S]*?)</pre>`));
  if (!match) throw new Error(`Missing published ${id} block; no tokens written.`);
  return decode(match[1]);
}
const published = JSON.parse(block("tokens-json"));
if (published.site !== "amazon.in" || published.colours.length !== 16) {
  throw new Error("Unexpected guide identity or palette; review the source before updating.");
}
const variables = Object.fromEntries([...block("tokens-css").matchAll(/--([a-z0-9-]+):\s*([^;{}]+);/g)]
  .map(([, name, value]) => [name, value.trim()]));
// The published gradient uses obsolete syntax. Keep it in the manifest;
// normalize the generated runtime CSS to modern browser syntax.
const css = Object.entries(variables).map(([name, value]) => {
  if (/url\(|@|[<>]/i.test(value)) throw new Error(`Unexpected CSS value: ${name}`);
  return `  --ssg-${name}: ${value.replace("linear-gradient(top,", "linear-gradient(to bottom,")};`;
}).join("\n");
const imagePaths = [...html.matchAll(/<img[^>]+src="([^"]+)"/g)].map((match) => match[1]);
const assetPath = (suffix) => {
  const path = imagePaths.find((value) => value.includes("/media/amazon.in/") && value.endsWith(suffix));
  if (!path) throw new Error(`Missing ${suffix} asset`);
  return new URL(path, source).href;
};
const logoUrl = assetPath("/logo.png");
const faviconUrl = assetPath("/icon-0.ico");
const [logo, favicon] = await Promise.all([download(logoUrl), download(faviconUrl)]);
if (logo.readUInt32BE(0) !== 0x89504e47 || favicon.readUInt32LE(0) !== 0x00010000) {
  throw new Error("Unexpected asset formats; no files written.");
}
const manifest = {
  ...published,
  retrievedAt: new Date().toISOString(),
  variables,
  shadows: ["0 0 0 3px #2162a1,0 0 0 6px #fff", "0 2px 5px 0 rgba(213,217,217,.5)", "0 2px 5px 0 hsla(180,5%,84%,.5)", "0 4px 4px rgba(0,0,0,.06)"],
  assets: [
    { source: logoUrl, path: "Docs/reference/amazon-in-labelled-logo.png", sha256: createHash("sha256").update(logo).digest("hex"), applied: false, reason: "Guide-labelled logo archived for visual review; never automatically applied to storefront branding." },
    { source: faviconUrl, path: "Frontend/public/brand/amazon-reference.ico", sha256: createHash("sha256").update(favicon).digest("hex"), applied: true },
  ],
  fonts: published.fonts.map((font) => ({ ...font, binaryProvidedByGuide: false })),
  limitations: ["Unofficial desktop capture; breakpoint values do not specify grid column counts.", "Guide font names are metadata, not downloadable Ember font files.", "Shadows transcribed from the Elements section; token variables parsed from published CSS."],
};
await Promise.all(["Docs/reference", "Frontend/src/styles/reference", "Frontend/public/brand"].map((path) => mkdir(resolve(root, path), { recursive: true })));
await writeFile(resolve(root, "Docs/reference/amazon-in.json"), JSON.stringify(manifest, null, 2) + "\n");
await writeFile(resolve(root, "Docs/reference/amazon-in-labelled-logo.png"), logo);
await writeFile(resolve(root, "Frontend/public/brand/amazon-reference.ico"), favicon);
await writeFile(resolve(root, "Frontend/src/styles/reference/amazon-in.tokens.css"), `/* Generated by scripts/scrape-amazon-reference.mjs from ${source}. */\n:root {\n${css}\n}\n`);
console.log(`Extracted ${published.colours.length} colors, ${Object.keys(variables).length} variables, ${published.fonts.length} font stacks and 2 inspected asset records.`);
